// Command ads2css writes the CSS file that connects an app's Tailwind build to the
// design system module: it imports the module's ads2.css (theme, fonts' tokens,
// shadcn styles) and adds @source lines for its components and patterns, so
// Tailwind generates every class they use.
//
// The module lives in the Go module cache, at a path that changes with every
// version and differs per machine, so the file is generated, not committed. Run it
// before every Tailwind build, from the app's module root:
//
//	go get -tool github.com/tilraunastofan/ads2/cmd/ads2css
//	go tool ads2css                        # writes assets/css/ads2.gen.css
//	tailwindcss -i assets/css/globals.css -o assets/css/output.css
//
// with globals.css starting
//
//	@import "tailwindcss";
//	@import "./ads2.gen.css";
//
// It asks the go command where the module is, so it follows go.mod, including a
// replace directive pointing at a local checkout.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const module = "github.com/tilraunastofan/ads2"

func main() {
	out := flag.String("o", filepath.Join("assets", "css", "ads2.gen.css"), "file to write")
	flag.Parse()
	dir, version, err := moduleDir()
	if err != nil {
		fmt.Fprintln(os.Stderr, "ads2css:", err)
		os.Exit(1)
	}
	css, err := generate(dir, version)
	if err != nil {
		fmt.Fprintln(os.Stderr, "ads2css:", err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "ads2css:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(css), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "ads2css:", err)
		os.Exit(1)
	}
}

// generate is the file's content for the module at dir.
func generate(dir, version string) (string, error) {
	d := filepath.ToSlash(dir)
	if strings.ContainsAny(d, "\"\\\n") {
		return "", fmt.Errorf("module path %q cannot be written as a CSS string", d)
	}
	if _, err := os.Stat(filepath.Join(dir, "assets", "css", "ads2.css")); err != nil {
		return "", fmt.Errorf("%s %s has no assets/css/ads2.css; it is older than the module setup, run go get %s@latest", module, version, module)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "/* Generated by `go tool ads2css` for %s %s. Do not edit or commit:\n", module, version)
	b.WriteString("   the path is this machine's Go module cache. Regenerate after go get. */\n")
	fmt.Fprintf(&b, "@import \"%s/assets/css/ads2.css\";\n", d)
	for _, src := range []string{"components", "patterns", "assets/js"} {
		fmt.Fprintf(&b, "@source \"%s/%s\";\n", d, src)
	}
	return b.String(), nil
}

// moduleDir asks the go command where the design system module is, downloading it
// if go.mod requires it but the cache doesn't have it yet.
func moduleDir() (dir, version string, err error) {
	var m struct{ Dir, Version string }
	run := func(args ...string) error {
		var stdout, stderr bytes.Buffer
		cmd := exec.Command("go", args...)
		cmd.Stdout, cmd.Stderr = &stdout, &stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("go %s: %v: %s", strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
		}
		return json.Unmarshal(stdout.Bytes(), &m)
	}
	if err := run("list", "-m", "-json", module); err != nil {
		return "", "", fmt.Errorf("%w (is %s in this module's go.mod? run go get %s)", err, module, module)
	}
	if m.Dir == "" {
		if err := run("mod", "download", "-json", module); err != nil {
			return "", "", err
		}
	}
	if m.Dir == "" {
		return "", "", errors.New("the go command did not report a directory for " + module)
	}
	if m.Version == "" {
		m.Version = "(local)"
	}
	return m.Dir, m.Version, nil
}
