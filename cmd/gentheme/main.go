// Command gentheme turns tokens/tokens.json (the Arion Design System 2 token file)
// into assets/css/arion-theme.css: the :root / .dark / @theme inline blocks that
// shadcn-templ v2 components read.
//
//	go run ./cmd/gentheme                       # default paths
//	go run ./cmd/gentheme -in tokens/tokens.json -out assets/css/arion-theme.css
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"
)

type token struct {
	Name  string          `json:"name"`
	Value json.RawMessage `json:"value"`
}

type tokens struct {
	Color struct {
		Themes []struct {
			ID string `json:"id"`
		} `json:"themes"`
		Tokens []token `json:"tokens"`
	} `json:"color"`
	Type struct {
		Families map[string]string `json:"families"`
	} `json:"type"`
	Radius struct {
		Tokens []struct {
			Name  string `json:"name"`
			Value string `json:"value"`
		} `json:"tokens"`
	} `json:"radius"`
}

// value returns a color token's value for a theme; a plain string or a missing
// theme falls back to the first theme, as the design system defines.
func value(t token, theme, first string) string {
	var s string
	if json.Unmarshal(t.Value, &s) == nil {
		return s
	}
	var m map[string]string
	if err := json.Unmarshal(t.Value, &m); err != nil {
		log.Fatalf("token %s: %v", t.Name, err)
	}
	if v, ok := m[theme]; ok {
		return v
	}
	return m[first]
}

func main() {
	in := flag.String("in", "tokens/tokens.json", "token file")
	out := flag.String("out", "assets/css/arion-theme.css", "css output")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	var tk tokens
	if err := json.Unmarshal(raw, &tk); err != nil {
		log.Fatal(err)
	}
	first := tk.Color.Themes[0].ID

	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	w("/* Arion Design System 2 — theme for shadcn-templ v2 (Tailwind v4).")
	w("   Generated by cmd/gentheme from %s. Do not edit by hand. */", *in)
	w("")
	w(`@custom-variant dark (&:is(.dark *, [data-theme="dark"] *));`)
	w("")
	w("@theme inline {")
	w("  --font-sans: var(--font-sans);")
	w("  --font-display: var(--font-display);")
	w("  --font-heading: var(--font-sans);")
	w("  --font-mono: var(--font-mono);")
	for _, k := range []string{"sm", "md", "lg", "xl"} {
		w("  --radius-%s: var(--radius-%s);", k, k)
	}
	w("  --radius-2xl: calc(var(--radius) * 1.8);")
	w("  --radius-3xl: calc(var(--radius) * 2.2);")
	w("  --radius-4xl: calc(var(--radius) * 2.6);")
	for _, t := range tk.Color.Tokens {
		w("  --color-%s: var(--%s);", t.Name, t.Name)
	}
	w("}")
	w("")
	w(":root {")
	for _, k := range []string{"sans", "display", "mono"} {
		if v, ok := tk.Type.Families[k]; ok {
			w("  --font-%s: %s;", k, v)
		}
	}
	for _, r := range tk.Radius.Tokens {
		if r.Name == "radius-full" {
			continue
		}
		w("  --%s: %s;", r.Name, r.Value)
	}
	for _, t := range tk.Color.Tokens {
		w("  --%s: %s;", t.Name, value(t, first, first))
	}
	w("}")
	for _, th := range tk.Color.Themes[1:] {
		w("")
		sel := "." + th.ID
		w("%s {", sel)
		for _, t := range tk.Color.Tokens {
			w("  --%s: %s;", t.Name, value(t, th.ID, first))
		}
		w("}")
	}
	w("")
	w("@layer base {")
	w("  * { @apply border-border outline-ring/50; }")
	w("  ::selection { @apply bg-selection text-selection-foreground; }")
	w("  body { @apply bg-background text-foreground font-sans; font-synthesis-weight: none; text-rendering: optimizeLegibility; }")
	w("  .cn-font-heading { @apply font-heading; }")
	w("}")

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s (%d color tokens)", *out, len(tk.Color.Tokens))
}
